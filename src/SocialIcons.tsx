export const renderSocialIcon = (name: string, props?: React.SVGProps<SVGSVGElement>) => {
  switch (name.toLowerCase()) {
    case 'github':
      return <GithubIcon {...props} />;
    case 'discord':
      return <DiscordIcon {...props} />;
    case 'whatsapp':
      return <WhatsAppIcon {...props} />;
    case 'tiktok':
      return <TikTokIcon {...props} />;
    case 'instagram':
      return <InstagramIcon {...props} />;
    case 'email':
    case 'mail':
      return <EmailIcon {...props} />;
    default:
      return null;
  }
};
